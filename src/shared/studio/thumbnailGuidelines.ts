export const SEED_GUIDELINES = `# Thumbnail guidelines

## YouTube long form
- 1280x720, 16:9, 2 MB or less, JPG or PNG.
- One clear subject. 3 to 5 words of large bold text at most. High contrast.
- Readable at tiny phone sizes. Consistent brand style across the channel.
- A clear promise that the video actually delivers. A misleading thumbnail raises clicks but hurts retention and watch time, so never overpromise.
- Emotion and curiosity are good. False claims are not.

## Wonder Hollow Workshop (made for kids)
- Bright, friendly characters. Simple.
- No scary or shocking imagery. No clickbait faces.
- Show the counted objects or the lesson when it helps.

## Shorts and Reels
- The first frame and the cover frame must work alone.
- YouTube Shorts: custom thumbnails cannot be uploaded through the API. Design the opening frame of the video so the frame YouTube picks is strong.
- TikTok: choose the best frame with the cover timestamp.
- Instagram: make a custom cover that also survives the center crop to a 1080x1080 square. Keep the text in the middle.

## Bluesky
- A strong first frame, or an image card, that fits its layout.
`
